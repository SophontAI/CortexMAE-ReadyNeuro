#!/usr/bin/env python3
"""Regenerate openneuro_1520h.yaml, the OpenNeuro subset matched to HCP-YA by hours.

An OpenNeuro subject carries 0.75 h of BOLD against 1.68 h for an HCP-YA one, so a
subject-matched pairing is hours-mismatched by 2.2x. Selection is whole batches in
index order, seeded-shuffled within each, and the subset is a prefix of that order --
which is what makes every subset nest inside the next. b31 is the validation holdout
and never appears.

It reads manifests/openneuro_rebuild_manifest.jsonl.gz from a ReadyNeuro
clone beside this repository (../ReadyNeuro); $OPENNEURO_MANIFEST overrides the path. The manifest's `bytes` column
gives a byte estimate of hours that runs high; the subset it selects has 1,520 h
measured from the run sidecars, which is the number that names the file.

Shards of studies flagged in the `withdrawn` column of
manifests/corpus_manifest.tsv in ReadyNeuro are written commented out: the paper
trained on them, but the public bucket does not serve them.
"""

import csv
import gzip
import json
import os
import random
from pathlib import Path

MANIFEST = Path(os.environ.get(
    "OPENNEURO_MANIFEST",
    Path(__file__).resolve().parents[3] / "ReadyNeuro/manifests/openneuro_rebuild_manifest.jsonl.gz",
))
CORPUS = Path(__file__).resolve().parents[3] / "ReadyNeuro/manifests/corpus_manifest.tsv"
OUTPUT = Path(__file__).parent / "openneuro_1520h.yaml"
BUCKET = "s3://openneuro/v1/openneuro-pretrain-shards-v6"
VOXELS = 183_000
HELD_OUT = "b31"
SEED = 42
# 880 HCP-YA subjects at 1.823 h each, in the manifest's byte estimate.
TARGET_HOURS = 1604


def load() -> list[dict]:
    records = []
    with gzip.open(MANIFEST, "rt") as handle:
        handle.readline()  # _meta
        for line in handle:
            record = json.loads(line)
            if record["batch"] != HELD_OUT:
                records.append(record)
    return records


def nested_order(records: list[dict]) -> list[dict]:
    """Whole batches in index order, shuffled within each -- so every prefix nests."""
    by_batch: dict[int, list[dict]] = {}
    for record in records:
        index = 0 if record["batch"] == "b0" else int(record["batch"][1:])
        by_batch.setdefault(index, []).append(record)
    order = []
    for index in sorted(by_batch):
        batch = sorted(by_batch[index], key=lambda r: r["shard"])
        random.Random(SEED + index).shuffle(batch)
        order.extend(batch)
    return order


def withdrawn() -> set[str]:
    with open(CORPUS, newline="") as handle:
        return {row["accession"] for row in csv.DictReader(handle, delimiter="\t") if row["withdrawn"] == "yes"}


def study(record: dict) -> str:
    return record["shard"].split("__")[0]


def url(record: dict) -> str:
    stem = BUCKET if record["batch"] == "b0" else f"{BUCKET}-{record['batch']}"
    return f"{stem}/train/native/{record['shard']}.tar"


def main() -> None:
    hours, chosen = 0.0, []
    for record in nested_order(load()):
        if hours >= TARGET_HOURS:
            break
        hours += record["bytes"] / VOXELS / 3600
        chosen.append(record)
    studies = len({study(record) for record in chosen})
    gone = withdrawn()
    public = [record for record in chosen if study(record) not in gone]
    dropped = len(chosen) - len(public)
    dropped_studies = studies - len({study(record) for record in public})
    urls = "\n".join(
        f"    # - {url(record)}  # withdrawn from OpenNeuro" if study(record) in gone else f"    - {url(record)}"
        for record in chosen
    )
    OUTPUT.write_text(
        f"# OpenNeuro subset: {len(chosen):,} within-study subject IDs, {studies} studies, 1,520 h of\n"
        f"# stored BOLD -- the point that matches the 880-subject HCP arm by hours.\n"
        f"# Nested inside every larger subset. Enumerated shard by shard because it cuts\n"
        f"# across a batch boundary; generated by make_openneuro_hours_urls.py.\n"
        f"# {dropped} shards from {dropped_studies} studies since withdrawn from OpenNeuro are commented out\n"
        f"# below and are not in the public bucket. The paper trained on all {len(chosen):,}; the public\n"
        # 1,502 h is sidecar-measured, like the 1,520 h above; the byte estimate cannot give it.
        f"# bucket serves the remaining {len(public):,} ({studies - dropped_studies} studies, 1,502 h).\n"        f"data:\n  urls:\n{urls}\n"
    )
    print(f"{OUTPUT.name}: {len(chosen):,} subjects, {studies} studies")


if __name__ == "__main__":
    main()
